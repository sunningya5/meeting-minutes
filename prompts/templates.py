"""
Prompt 模板
对标飞书妙记 — 结构化会议纪要输出
"""

# ============================================================
# 妙记风格 Prompt（主模板）
# ============================================================
FEISHU_MINUTES_PROMPT = """你是一个专业会议纪要助手。请根据以下会议录音转写，生成一份结构**清晰、信息完整**的会议纪要。输出格式严格遵循下方模板。

## 转写文本
{transcript}

## 输出格式要求

请严格按以下结构输出，使用 Markdown 格式：

---

## 智能摘要

用 2-3 句话概括本次会议的核心内容和结论。

## 关键词

提取 5-8 个会议关键词，用「·」分隔。

## 章节速览

根据内容变化，将会议切分为 3-8 个话题章节，每个章节给一个标题。格式：

- [00:00] 章节标题
- [MM:SS] 章节标题

（时间戳请根据转写内容中提到的位置估算，如无时间信息则只写标题）

## 讨论要点

列出会议中讨论的主要话题，每条包含：
- **话题标题**：简明描述 + 关键讨论内容和结论

共 3-8 条。

## 待办事项

从会议内容中提取所有待办和行动项，格式：

- [ ] **任务描述** @负责人（如有提及） 📅 截止时间（如有提及）

如果未提及负责人或时间，则只写任务描述。如完全没有待办事项，写「（本次会议无明确待办事项）」。

## 会议全文

将上方转写文本整理为更易读的段落格式。可以适当合并相关语句，但保留原意。用空行分隔不同话题段落。"""


# ============================================================
# 简版（短会议 / 转写质量不高时用）
# ============================================================
FEISHU_MINUTES_SIMPLE = """根据以下会议转写，生成结构化会议纪要。

转写内容：
{transcript}

请输出：
## 智能摘要
（1-2句话概括）

## 关键词
（3-5个，用·分隔）

## 章节速览
（3-5个话题章节）

## 讨论要点
（3-5条核心观点）

## 待办事项
（列出行动项，无则写「无」）"""


# ============================================================
# 标题提取
# ============================================================
TITLE_PROMPT = """根据以下会议转写，生成一个精炼的会议标题（15字以内，不要引号）：

{transcript}

标题："""


def build_feishu_prompt(transcript: str, use_simple: bool = False) -> str:
    """构建飞书妙记风格 Prompt"""
    if len(transcript) < 200 or use_simple:
        return FEISHU_MINUTES_SIMPLE.format(transcript=transcript)
    return FEISHU_MINUTES_PROMPT.format(transcript=transcript)


def build_title_prompt(transcript: str) -> str:
    snippet = transcript[:500] if len(transcript) > 500 else transcript
    return TITLE_PROMPT.format(transcript=snippet)
